local sandbox = {}
for k, v in pairs(getfenv and getfenv(0) or _ENV) do
    sandbox[k] = v
end

-- Giả lập môi trường Roblox tối thiểu để đánh lừa VM
sandbox.game = {
    GetService = function() return setmetatable({}, {__index = function() return function() end end}) end,
    PlaceId = 0,
    JobId = "faked"
}
sandbox.workspace = {}
sandbox.script = { Disabled = false }
sandbox.task = { spawn = function(f) f() end, defer = function(f) f() end, wait = function() end }

-- Hàm bắt giữ chuỗi đã giải mã
local function dump_code(str)
    if type(str) == "string" and string.len(str) > 20 then
        -- Lọc bỏ các chuỗi rác hệ thống của VM
        if not string.find(str, "J%(") and not string.find(str, "RH%[") then
            print("\n============================================================")
            print("  MÃ NGUỒN SCRIPT ROBLOX ĐÃ GIẢI MÃ THÀNH CÔNG:")
            print("============================================================\n")
            print(str)
            print("\n============================================================")
            os.exit(0)
        end
    end
end

-- Tận dụng luồng thực thi để xuất dữ liệu mà không chỉnh sửa getfenv toàn cục
sandbox.loadstring = function(str, chunkname)
    dump_code(str)
    return function() end
end
sandbox.load = function(chunk, chunkname, mode, env)
    if type(chunk) == "string" then dump_code(chunk) end
    return function() end
end

